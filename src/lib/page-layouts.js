export function buildLayoutSections(presetId, business = {}) {
  const preset = PAGE_LAYOUT_PRESETS.find((p) => p.id === presetId) || PAGE_LAYOUT_PRESETS[0];
  const animProfile = ANIMATION_PROFILES[preset.id] || { type: "fade-up", duration: 0.8, easing: "power2.out", trigger: "scroll" };
  const palette = THEME_PALETTES[preset.id] || PREDEFINED_THEMES[preset.themeId] || PREDEFINED_THEMES["modern-business"];
  const images = getIndustryImages(preset.id);

  const theme = {
    ...palette,
    preset: preset.themeId,
  };

  const sections = preset.sectionTypes.map((item, idx) => {
    // Generate base section with requested layout variation
    const sec = createDefaultSection(item.type, item.layout, business);

    // Apply custom animation profile tailored to this preset
    sec.animations = {
      ...sec.animations,
      ...animProfile,
      delay: idx === 0 ? 0 : 0.05,
    };

    // Apply industry-specific high quality imagery
    if (item.type === "hero" || item.type === "hero_bg_image" || item.type === "hero_bg_video") {
      sec.content.imageUrl = images.hero || images.heroFallback;
    }

    if (item.type === "about" && images.about) {
      sec.content.imageUrl = images.about;
    }

    if (item.type === "services" && images.services) {
      sec.content.items = sec.content.items?.map((serv, sIdx) => ({
        ...serv,
        imageUrl: images.services[sIdx % images.services.length]?.image || images.about,
      })) || [];
    }

    if (item.type === "product_showcase" && images.showcase) {
      sec.content.items = images.showcase.map((p, pIdx) => ({
        name: p.name,
        price: p.price,
        imageUrl: p.image,
        description: `Handcrafted and engineered with premium grade materials, verified testing, and manufacturer warranty.`,
        badge: pIdx === 0 ? "Featured Choice" : "Best Value",
      }));
    }

    if (item.type === "product_grid" && images.services) {
      sec.content.items = sec.content.items?.map((p, pIdx) => ({
        ...p,
        image: images.services[pIdx % images.services.length]?.image || images.about,
      })) || [];
    }

    if (item.type === "gallery" && images.gallery) {
      sec.content.images = images.gallery;
    }

    if (item.type === "owner_profile" && images.owner) {
      sec.content.imageUrl = images.owner;
    }

    if (item.type === "team_members" && images.team) {
      sec.content.members = images.team;
    }

    // Preset-specific customization touches
    if (item.type === "header_navigation") {
      sec.layout = preset.navbarType || item.layout;
      if (preset.navbarType === "solid_dark") {
        sec.styles.backgroundColor = palette.secondaryColor;
        sec.styles.textColor = "#FFFFFF";
      } else if (preset.navbarType === "transparent") {
        sec.styles.backgroundColor = "transparent";
      }
    }

    if (item.type === "announcement_bar") {
      if (item.layout === "gradient") {
        sec.styles.backgroundColor = palette.primaryColor;
        sec.styles.textColor = "#FFFFFF";
      } else if (item.layout === "ticker") {
        sec.styles.backgroundColor = palette.secondaryColor;
        sec.styles.textColor = palette.accentColor;
      }
    }

    if (item.type === "statistics") {
      sec.styles.backgroundColor = palette.secondaryColor;
      sec.styles.textColor = "#FFFFFF";
    }

    return sec;
  });

  return {
    sections,
    theme,
  };
}
